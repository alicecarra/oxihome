const HTMX: &str = include_str!("../../static/htmx.min.js");
const HTMX_SSE: &str = include_str!("../../static/htmx-ext-sse.min.js");
const CONFIG_EDITOR: &str = include_str!("../../static/config-editor.js");
const FILTER: &str = include_str!("../../static/filter.js");
const NODE_SORT: &str = include_str!("../../static/node-sort.js");
const REMOTE_CODES: &str = include_str!("../../static/remote-codes.js");
const TRAFFIC: &str = include_str!("../../static/traffic.js");
/// Generated by build.rs from styles.css.
const STYLESHEET: &str = include_str!(concat!(env!("OUT_DIR"), "/tailwind.css"));

/// `listen_host` is the `[http] host` the hub binds to: requests must name it, one of
/// `allowed_hosts`, or localhost.
pub fn router(hub: Arc<Hub>, auth: Auth, listen_host: &str, allowed_hosts: &[String]) -> Router {
    Router::builder()
        .layer(host::HostLayer::new(listen_host, allowed_hosts))
        // Registered before the session and cookie layers so it runs inside them.
        .layer(auth::AuthLayer)
        .sessions(SessionConfig::builder().lifetime(auth::LIFETIME).build())
        .cookies()
        .page(auth::login_page)
        .page(dashboard::dashboard_page)
        .page(dashboard::dashboard_fragment)
        .page(dashboard::dashboard_block_fragment)
        .page(nodes::nodes_page)
        .page(nodes::nodes_fragment)
        .page(node::node_page)
        .page(node::overview_fragment)
        .page(node::overview_edit_fragment)
        .page(node::fields_fragment)
        .page(node::fields_edit_fragment)
        .page(node::history_fragment)
        .page(node::hardware_fragment)
        .page(rules::rules)
        .page(rules::indicator_fragment)
        .page(rules::new_rule)
        .page(rules::edit_rule)
        .page(timeline::timeline)
        .page(timeline::timeline_fragment)
        .page(timeline::timeline_more)
        .page(remotes::remotes_page)
        .page(remotes::remotes_fragment)
        .page(settings::settings)
        .page(settings::settings_file)
        .page(tools::lab::lab)
        .page(tools::tools)
        .page(tools::network_page)
        .page(tools::network_fragment)
        .page(tools::traffic_page)
        .page(tools::traffic_map_fragment)
        .route(auth::login)
        .route(auth::logout)
        .route(home::set)
        .route(rules::set_enabled)
        .route(rules::run_now)
        .route(rules::redraw)
        .route(rules::save)
        .route(node::edit)
        .route(node::start_update)
        .route(node::forget)
        .route(node::entities_download)
        .route(home::invoke)
        .route(remotes::learn_key)
        .route(remotes::forget_key)
        .route(remotes::send_code)
        .route(dashboard::press)
        .route(settings::reload)
        .route(settings::save)
        .route(toasts::toasts)
        .route(changes::events)
        .route(tools::traffic_events)
        .route(htmx_script)
        .route(htmx_sse_script)
        .route(config_editor_script)
        .route(filter_script)
        .route(node_sort_script)
        .route(remote_codes_script)
        .route(traffic_script)
        .route(stylesheet)
        .route(install::manifest)
        .route(install::service_worker)
        .route(install::registration)
        .route(install::icon_192)
        .route(install::icon_512)
        .app_context(hub)
        .app_context(auth)
        .build()
}

